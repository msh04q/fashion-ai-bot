    async def get_local_outfit(self, style: str, season: str, occasion: str, gender: str, budget: str) -> Dict:
        """Получить локальный образ одежды"""
        
        logger.info(f"Поиск локального образа: {style}, {season}, {occasion}, {gender}")
        
        # Поиск подходящего образа
        for outfit in self.outfits_database:
            if (outfit["style"] in style.lower() and 
                outfit["season"] in season.lower() and 
                outfit["occasion"] in occasion.lower() and
                (outfit["gender"] == "унисекс" or outfit["gender"] in gender.lower())):
                
                outfit_copy = outfit.copy()
                
                # Адаптируем под бюджет
                budget_tip = outfit_copy.get("budget_tips", {}).get(budget.lower(), "")
                if budget_tip:
                    outfit_copy["tips"].append(f"Бюджет: {budget_tip}")
                
                outfit_copy["has_ai"] = False
                return outfit_copy
        
        # Если не нашли, создаем общий образ
        return self._create_general_outfit(style, season, occasion, gender, budget)
    
